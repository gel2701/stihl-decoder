export function buildAndValidatePhase60Candidates() {
  const partsCatalogPath = path.join(rootDir, 'data', 'parts_catalog.json');
  const catalog = JSON.parse(fs.readFileSync(partsCatalogPath, 'utf8'));
  const catalogPartMap = new Set(catalog.parts.map(p => p.part_number));

  const validatedCandidates = [];
  const gateMetrics = {
    total: PHASE60_RAW_CANDIDATES.length,
    gate1_pass: 0,
    gate1_fail: 0,
    gate2_pass: 0,
    gate2_fail: 0,
    fully_verified: 0,
    active_in_production: 0,
    staged_ready: 0
  };

  for (const c of PHASE60_RAW_CANDIDATES) {
    const candidateWithDate = {
      ...c,
      verification_date: c.verification_date || '2026-11-03'
    };
    const normPart = PartNormalizer.normalizePartNumber(c.part_number);
    const g1 = TwoGateVerifier.evaluateGate1(candidateWithDate, { catalogPartMap, expectedTag: 'srihldecoder2-21' });
    const g2 = TwoGateVerifier.evaluateGate2(candidateWithDate);

    if (g1.passed) gateMetrics.gate1_pass++;
    else gateMetrics.gate1_fail++;

    if (g2.passed) gateMetrics.gate2_pass++;
    else gateMetrics.gate2_fail++;

    const fullyVerified = g1.passed && g2.passed;
    if (fullyVerified) {
      gateMetrics.fully_verified++;
      if (c.status === 'ACTIVE') gateMetrics.active_in_production++;
      else gateMetrics.staged_ready++;
    }

    validatedCandidates.push({
      ...c,
      part_number: normPart,
      gate_1: { passed: g1.passed, checks: g1.checks, errors: g1.errors },
      gate_2: { passed: g2.passed, checks: g2.checks, errors: g2.errors },
      two_gate_status: fullyVerified ? 'PASS' : 'FAIL',
      activation_eligibility: fullyVerified ? 'READY_FOR_OPERATOR_AUTHORIZATION' : 'SUSPENDED_DEFECTIVE'
    });
  }

  return {
    phase: '60',
    generated_at: new Date().toISOString(),
    policy: {
      pilot_lock: 'PRESERVED_MAX_3_ACTIVE_ASINS',
      authorized_active_asins: ['B0068M5NAG', 'B001RM8J76', 'B001RMA5S2'],
      operator_authorization_required_for_staged: true,
      affiliate_tag: 'srihldecoder2-21'
    },
    metrics: gateMetrics,
    candidates: validatedCandidates
  };
}

if (process.argv[1] && process.argv[1].endsWith('build_phase60_candidates.mjs')) {
  const result = buildAndValidatePhase60Candidates();
  const outPath = path.join(rootDir, 'PHASE60_AMAZON_MATCHING_CANDIDATES.json');
  fs.writeFileSync(outPath, JSON.stringify(result, null, 2), 'utf8');

  console.log('===============================================================');
  console.log('📦 PHASE 60 — AMAZON AFFILIATE MATCHING BATCH EVALUATION');
  console.log('===============================================================');
  console.log(`Total Candidates Evaluated: ${result.metrics.total}`);
  console.log(`Gate 1 (Technical & Catalog) Passed: ${result.metrics.gate1_pass}/${result.metrics.total}`);
  console.log(`Gate 2 (Product & Compatibility) Passed: ${result.metrics.gate2_pass}/${result.metrics.total}`);
  console.log(`Fully Verified Candidates: ${result.metrics.fully_verified}`);
  console.log(`Active Live Pilots Preserved: ${result.metrics.active_in_production} (Lock: 3 max)`);
  console.log(`Staged Ready for Operator Approval: ${result.metrics.staged_ready}`);
  console.log(`Dossier Saved: ${outPath}`);
  console.log('===============================================================');
}
